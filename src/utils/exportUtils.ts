/**
 * Utility functions for exporting data to Excel (.csv), Word (.doc), and printable PDF/Receipts.
 */

export function exportToCSV(dataOrFilename: any, headersOrFilename?: any, rows?: any) {
  let csvContent = '';
  let filename = 'BSWA_Export';

  if (Array.isArray(dataOrFilename) && typeof dataOrFilename[0] === 'object' && !Array.isArray(dataOrFilename[0])) {
    // Array of objects format: exportToCSV(arrayOfObjects, 'filename')
    filename = typeof headersOrFilename === 'string' ? headersOrFilename : 'BSWA_Export';
    const items = dataOrFilename;
    if (items.length === 0) return;
    const headers = Object.keys(items[0]);
    const headerRow = headers.map(h => `"${h.replace(/"/g, '""')}"`).join(',');
    const bodyRows = items.map(item =>
      headers.map(h => `"${String(item[h] ?? '').replace(/"/g, '""')}"`).join(',')
    );
    csvContent = [headerRow, ...bodyRows].join('\r\n');
  } else if (typeof dataOrFilename === 'string' && Array.isArray(headersOrFilename) && Array.isArray(rows)) {
    // Legacy format: exportToCSV(filename, headers, rows)
    filename = dataOrFilename;
    const headers = headersOrFilename as string[];
    const rowList = rows as (string | number)[][];
    csvContent = [
      headers.map(h => `"${h.replace(/"/g, '""')}"`).join(','),
      ...rowList.map(row =>
        row.map(cell => `"${String(cell ?? '').replace(/"/g, '""')}"`).join(',')
      )
    ].join('\r\n');
  }

  const blob = new Blob(['\uFEFF' + csvContent], { type: 'text/csv;charset=utf-8;' });
  const link = document.createElement('a');
  link.href = URL.createObjectURL(blob);
  link.setAttribute('download', `${filename}.csv`);
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
}

