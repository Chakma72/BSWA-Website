export const exportToWordDoc = exportToWord;

export function exportToPrintablePDF(title: string, elementIdOrHtml: string) {
  let content = elementIdOrHtml;
  const el = document.getElementById(elementIdOrHtml);
  if (el) {
    content = el.innerHTML;
  }
  openPrintableDocument(title, content);
}

